    @CommandHandler
    public void handle(AssignCampaignToExperimentCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignCampaignToExperimentCommand" );
    	
    	if (  campaign != null && campaign.getCampaignId() == command.getAssignment().getCampaignId() )
    		throw new ProcessingException( "Campaign already assigned with id " + command.getAssignment().getCampaignId() );  
    		
        apply(new AssignCampaignToExperimentEvent(command.getExperimentId(), command.getAssignment()));
    }

