@Aggregate
public class BrandAggregate {  

	// -----------------------------------------
	// Axon requires an empty constructor
    // -----------------------------------------
    public BrandAggregate() {
    }

	// ----------------------------------------------
	// intrinsic command handlers
	// ----------------------------------------------
    @CommandHandler
    public BrandAggregate(CreateBrandCommand command) throws Exception {
    	LOGGER.info( "Handling command CreateBrandCommand" );
    	CreateBrandEvent event = new CreateBrandEvent(command.getBrandId(), command.getName(), command.getDescription(), command.getWebsite());
    	
        apply(event);
    }

    @CommandHandler
    public void handle(UpdateBrandCommand command) throws Exception {
    	LOGGER.info( "handling command UpdateBrandCommand" );
    	UpdateBrandEvent event = new UpdateBrandEvent(command.getBrandId(), command.getName(), command.getDescription(), command.getWebsite(), command.getMerchant(), command.getProducts());        
    	
        apply(event);
    }

    @CommandHandler
    public void handle(DeleteBrandCommand command) throws Exception {
    	LOGGER.info( "Handling command DeleteBrandCommand" );
        apply(new DeleteBrandEvent(command.getBrandId()));
    }

	// ----------------------------------------------
	// association command handlers
	// ----------------------------------------------

    // single association commands
    @CommandHandler
    public void handle(AssignMerchantToBrandCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignMerchantToBrandCommand" );
    	
    	if (  merchant != null && merchant.getMerchantId() == command.getAssignment().getMerchantId() )
    		throw new ProcessingException( "Merchant already assigned with id " + command.getAssignment().getMerchantId() );  
    		
        apply(new AssignMerchantToBrandEvent(command.getBrandId(), command.getAssignment()));
    }

    @CommandHandler
    public void handle(UnAssignMerchantFromBrandCommand command) throws Exception {
    	LOGGER.info( "Handlign command UnAssignMerchantFromBrandCommand" );

    	if (  merchant == null )
    		throw new ProcessingException( "Merchant already has nothing assigned." );  

    	apply(new UnAssignMerchantFromBrandEvent(command.getBrandId()));
    }

    // multiple association commands
    @CommandHandler
    public void handle(AssignProductsToBrandCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignProductsToBrandCommand" );
    	
    	if ( products.contains( command.getAddTo() ) )
    		throw new ProcessingException( "Products already contains an entity with id " + command.getAddTo().getProductId() );

    	apply(new AssignProductsToBrandEvent(command.getBrandId(), command.getAddTo()));
    }

    @CommandHandler
    public void handle(RemoveProductsFromBrandCommand command) throws Exception {
    	LOGGER.info( "Handling command RemoveProductsFromBrandCommand" );
    	
    	if ( !products.contains( command.getRemoveFrom() ) )
    		throw new ProcessingException( "Products does not contain an entity with id " + command.getRemoveFrom().getProductId() );

        apply(new RemoveProductsFromBrandEvent(command.getBrandId(), command.getRemoveFrom()));
    }

	// ----------------------------------------------
	// intrinsic event source handlers
	// ----------------------------------------------
    @EventSourcingHandler
    void on(CreateBrandEvent event) {	
    	LOGGER.info( "Event sourcing CreateBrandEvent" );
    	this.brandId = event.getBrandId();
        this.name = event.getName();
        this.description = event.getDescription();
        this.website = event.getWebsite();
    }
    
    @EventSourcingHandler
    void on(UpdateBrandEvent event) {
    	LOGGER.info( "Event sourcing classObject.getUpdateEventAlias()}" );
        this.name = event.getName();
        this.description = event.getDescription();
        this.website = event.getWebsite();
        this.merchant = event.getMerchant();
        this.products = event.getProducts();
    }   

	// ----------------------------------------------
	// association event source handlers
	// ----------------------------------------------
	// single associations
    @EventSourcingHandler
    void on(AssignMerchantToBrandEvent event ) {	
    	LOGGER.info( "Event sourcing AssignMerchantToBrandEvent" );
    	this.merchant = event.getAssignment();
    }

	@EventSourcingHandler
	void on(UnAssignMerchantFromBrandEvent event ) {	
		LOGGER.info( "Event sourcing UnAssignMerchantFromBrandEvent" );
		this.merchant = null;
	}

	// multiple associations
    @EventSourcingHandler
    void on(AssignProductsToBrandEvent event ) {
    	LOGGER.info( "Event sourcing AssignProductsToBrandEvent" );
    	this.products.add( event.getAddTo() );
    }

	@EventSourcingHandler
	void on(RemoveProductsFromBrandEvent event ) {	
		LOGGER.info( "Event sourcing RemoveProductsFromBrandEvent" );
		this.products.remove( event.getRemoveFrom() );
	}
	

    // ------------------------------------------
    // attributes
    // ------------------------------------------
	
    @AggregateIdentifier
    private UUID brandId;
    
    private String name;
    private String description;
    private String website;
    private Merchant merchant = null;
    private Set<Product> products = new HashSet<>();

    private static final Logger LOGGER 	= Logger.getLogger(BrandAggregate.class.getName());
}
