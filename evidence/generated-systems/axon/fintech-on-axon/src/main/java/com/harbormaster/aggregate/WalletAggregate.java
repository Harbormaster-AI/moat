    @CommandHandler
    public WalletAggregate(CreateWalletCommand command) throws Exception {
    	LOGGER.info( "Handling command CreateWalletCommand" );
    	CreateWalletEvent event = new CreateWalletEvent(command.getWalletId(), command.getCurrency(), command.getBalance(), command.getStatus());
    	
        apply(event);
    }

    @CommandHandler
    public void handle(UpdateWalletCommand command) throws Exception {
    	LOGGER.info( "handling command UpdateWalletCommand" );
    	UpdateWalletEvent event = new UpdateWalletEvent(command.getWalletId(), command.getCurrency(), command.getBalance(), command.getCustomer(), command.getTransactions(), command.getStatus());        
    	
        apply(event);
    }

    @CommandHandler
    public void handle(DeleteWalletCommand command) throws Exception {
    	LOGGER.info( "Handling command DeleteWalletCommand" );
        apply(new DeleteWalletEvent(command.getWalletId()));
    }

	// ----------------------------------------------
	// association command handlers
	// ----------------------------------------------

    // single association commands
    @CommandHandler
    public void handle(AssignCustomerToWalletCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignCustomerToWalletCommand" );
    	
    	if (  customer != null && customer.getCustomerId() == command.getAssignment().getCustomerId() )
    		throw new ProcessingException( "Customer already assigned with id " + command.getAssignment().getCustomerId() );  
    		
        apply(new AssignCustomerToWalletEvent(command.getWalletId(), command.getAssignment()));
    }

    @CommandHandler
    public void handle(UnAssignCustomerFromWalletCommand command) throws Exception {
    	LOGGER.info( "Handlign command UnAssignCustomerFromWalletCommand" );

    	if (  customer == null )
    		throw new ProcessingException( "Customer already has nothing assigned." );  

    	apply(new UnAssignCustomerFromWalletEvent(command.getWalletId()));
    }

    // multiple association commands
    @CommandHandler
    public void handle(AssignTransactionsToWalletCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignTransactionsToWalletCommand" );
    	
    	if ( transactions.contains( command.getAddTo() ) )
    		throw new ProcessingException( "Transactions already contains an entity with id " + command.getAddTo().getTransactionId() );

    	apply(new AssignTransactionsToWalletEvent(command.getWalletId(), command.getAddTo()));
    }

    @CommandHandler
    public void handle(RemoveTransactionsFromWalletCommand command) throws Exception {
    	LOGGER.info( "Handling command RemoveTransactionsFromWalletCommand" );
    	
    	if ( !transactions.contains( command.getRemoveFrom() ) )
    		throw new ProcessingException( "Transactions does not contain an entity with id " + command.getRemoveFrom().getTransactionId() );

        apply(new RemoveTransactionsFromWalletEvent(command.getWalletId(), command.getRemoveFrom()));
    }

