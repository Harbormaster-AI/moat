	// ----------------------------------------------
	// association command handlers
	// ----------------------------------------------

    // single association commands
    @CommandHandler
    public void handle(AssignSiteToBuildingCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignSiteToBuildingCommand" );
    	
    	if (  site != null && site.getSiteId() == command.getAssignment().getSiteId() )
    		throw new ProcessingException( "Site already assigned with id " + command.getAssignment().getSiteId() );  
    		
        apply(new AssignSiteToBuildingEvent(command.getBuildingId(), command.getAssignment()));
    }

    @CommandHandler
    public void handle(UnAssignSiteFromBuildingCommand command) throws Exception {
    	LOGGER.info( "Handlign command UnAssignSiteFromBuildingCommand" );

    	if (  site == null )
    		throw new ProcessingException( "Site already has nothing assigned." );  

    	apply(new UnAssignSiteFromBuildingEvent(command.getBuildingId()));
    }

    // multiple association commands
    @CommandHandler
    public void handle(AssignFloorsToBuildingCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignFloorsToBuildingCommand" );
    	
    	if ( floors.contains( command.getAddTo() ) )
    		throw new ProcessingException( "Floors already contains an entity with id " + command.getAddTo().getFloorId() );

    	apply(new AssignFloorsToBuildingEvent(command.getBuildingId(), command.getAddTo()));
    }

    @CommandHandler
    public void handle(RemoveFloorsFromBuildingCommand command) throws Exception {
    	LOGGER.info( "Handling command RemoveFloorsFromBuildingCommand" );
    	
    	if ( !floors.contains( command.getRemoveFrom() ) )
    		throw new ProcessingException( "Floors does not contain an entity with id " + command.getRemoveFrom().getFloorId() );

        apply(new RemoveFloorsFromBuildingEvent(command.getBuildingId(), command.getRemoveFrom()));
    }

