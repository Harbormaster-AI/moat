	// association command handlers
	// ----------------------------------------------

    // single association commands
    @CommandHandler
    public void handle(AssignBuildingToFloorCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignBuildingToFloorCommand" );
    	
    	if (  building != null && building.getBuildingId() == command.getAssignment().getBuildingId() )
    		throw new ProcessingException( "Building already assigned with id " + command.getAssignment().getBuildingId() );  
    		
        apply(new AssignBuildingToFloorEvent(command.getFloorId(), command.getAssignment()));
    }

    @CommandHandler
    public void handle(UnAssignBuildingFromFloorCommand command) throws Exception {
    	LOGGER.info( "Handlign command UnAssignBuildingFromFloorCommand" );

    	if (  building == null )
    		throw new ProcessingException( "Building already has nothing assigned." );  

    	apply(new UnAssignBuildingFromFloorEvent(command.getFloorId()));
    }

    // multiple association commands
    @CommandHandler
    public void handle(AssignRoomsToFloorCommand command) throws Exception {
    	LOGGER.info( "Handling command AssignRoomsToFloorCommand" );
    	
    	if ( rooms.contains( command.getAddTo() ) )
    		throw new ProcessingException( "Rooms already contains an entity with id " + command.getAddTo().getRoomId() );

    	apply(new AssignRoomsToFloorEvent(command.getFloorId(), command.getAddTo()));
    }

    @CommandHandler
    public void handle(RemoveRoomsFromFloorCommand command) throws Exception {
    	LOGGER.info( "Handling command RemoveRoomsFromFloorCommand" );
    	
    	if ( !rooms.contains( command.getRemoveFrom() ) )
    		throw new ProcessingException( "Rooms does not contain an entity with id " + command.getRemoveFrom().getRoomId() );

        apply(new RemoveRoomsFromFloorEvent(command.getFloorId(), command.getRemoveFrom()));
    }

